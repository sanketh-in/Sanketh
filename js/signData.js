export function processText(text) {
  return text
    .toLowerCase()
    .replace(/[^\w\s]/g, "")
    .split(/\s+/)
    .filter(w => w.length > 0 && !STOP_WORDS.has(w));
}

export function lookupSign(word, mode = "ASL") {
  const dict = mode === "ISL" ? ISL_DICTIONARY : ASL_DICTIONARY;
  const lower = word.toLowerCase();
  if (dict[lower]) return dict[lower];
  // Safe plural/singular handling only (e.g. "books" -> "book").
  // NOTE: this used to do a raw substring match ("time".includes("me")),
  // which caused unrelated words to incorrectly show another word's sign.
  if (lower.endsWith("s") && dict[lower.slice(0, -1)]) return dict[lower.slice(0, -1)];
  if (dict[lower + "s"]) return dict[lower + "s"];
  return null;
}

const UNIQUE_FALLBACKS = {
  key0: "🤟", key1: "🖖", key2: "🤙", key3: "👊", key4: "✊",
  key5: "🤛", key6: "🤞", key7: "🫶", key8: "🫵", key9: "🫴",
};

let fallbackIndex = 0;
const wordFallbackMap = {};

export function getFallbackEmoji(word) {
  if (!wordFallbackMap[word]) {
    const keys = Object.keys(UNIQUE_FALLBACKS);
    wordFallbackMap[word] = UNIQUE_FALLBACKS[keys[fallbackIndex % keys.length]];
    fallbackIndex++;
  }
  return wordFallbackMap[word];
}

