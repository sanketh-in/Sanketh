export function getDictionaryEntries(mode = "ASL") {
  const dict = mode === "ISL" ? ISL_DICTIONARY : ASL_DICTIONARY;
  const seen = new Set();
  const result = [];
  for (const entry of Object.values(dict)) {
    if (!seen.has(entry.word)) {
      seen.add(entry.word);
      result.push(entry);
    }
  }
  return result.sort((a, b) => a.word.localeCompare(b.word));
}
